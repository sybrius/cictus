import mysql from 'mysql2/promise';
import { z } from 'zod';
import dns from 'node:dns/promises';
import net from 'node:net';
import type { ColumnInfo, DatabaseSchema, TableInfo, ViewInfo } from './sqlserver';

/**
 * MySQL source — the second migration source, next to SQL Server.
 *
 * Introspection reads `information_schema` only, and maps the result
 * onto the same TableInfo / ColumnInfo / ViewInfo shapes SQL Server
 * uses, so the DDL generator, the data copy and validation do not
 * care which source a table came from. The differences that matter:
 *
 * - MySQL has no schemas: the selected database maps to Postgres
 *   `public` (schema is set to 'public' below), so tables land where
 *   Hasura / the Supabase Table Editor expect them.
 * - `tinyint(1)` is MySQL's boolean (used by ORMs and WordPress-style
 *   schemas); other tinyints are smallints. `int unsigned` exceeds
 *   Postgres `integer`, so it becomes `bigint` (see type-map.ts).
 * - AUTO_INCREMENT columns become `GENERATED BY DEFAULT AS IDENTITY`
 *   and get their sequences re-seeded like SQL Server identities.
 * - Row counts are exact `COUNT(*)` per table: information_schema's
 *   TABLE_ROWS is only an InnoDB estimate and would make validation
 *   report false mismatches.
 * - MySQL `DATETIME` has no timezone, so it maps to `timestamp`
 *   (not timestamptz); `TIMESTAMP` maps to `timestamptz`.
 * - Views come from information_schema.VIEWS as a bare SELECT
 *   (no CREATE VIEW header); conversion to Postgres lives in ddl.ts
 *   (convertViewSql, dialect 'mysql').
 */

/** Connection settings supplied by the wizard (never stored server-side
 *  beyond the request that uses them). */
export const MysqlConfigSchema = z.object({
  host: z.string().min(1, 'Host is required'),
  port: z.coerce.number().int().min(1).max(65535).default(3306),
  user: z.string().min(1, 'User is required'),
  password: z.string().min(1, 'Password is required'),
  database: z.string().min(1, 'Database is required'),
  ssl: z.boolean().default(false),
});

export type MysqlConfig = z.infer<typeof MysqlConfigSchema>;

export type SourceKind = 'sqlserver' | 'mysql';

function toPoolConfig(cfg: MysqlConfig): mysql.PoolOptions {
  return {
    host: cfg.host,
    port: cfg.port,
    user: cfg.user,
    password: cfg.password,
    database: cfg.database,
    ssl: cfg.ssl ? { rejectUnauthorized: false } : undefined,
    waitForConnections: true,
    connectionLimit: 5,
    connectTimeout: 15_000,
    // BIGINT as strings (no precision loss past 2^53), DECIMAL as
    // strings (pg numeric accepts them) — both are exact this way.
    supportBigNumbers: true,
    bigNumberStrings: true,
  };
}

/** Plain-English explanation for the cryptic MySQL errors. */
export function explainMysqlError(err: unknown): string {
  const e = err as { code?: string; errno?: number; message?: string };
  const msg = e?.message ?? String(err);
  const code = e?.code ?? '';
  if (code === 'ER_ACCESS_DENIED_ERROR' || e?.errno === 1045) {
    return `${msg} — the server answered, but the login was rejected. Check the username/password, and that the MySQL user is allowed to connect from this host (a user created as 'app'@'localhost' cannot log in from another machine — create it as 'app'@'%' or the app's IP).`;
  }
  if (code === 'ER_BAD_DB_ERROR' || e?.errno === 1049) {
    return `${msg} — the database does not exist on that server. Check the Database name (it is case-sensitive on Linux).`;
  }
  if (code === 'ER_HOST_NOT_PRIVILEGED' || e?.errno === 1130) {
    return `${msg} — the MySQL server refuses connections from this host. Grant access: CREATE USER 'user'@'%' IDENTIFIED BY '…'; GRANT … ON db.* TO 'user'@'%'; — or run the app on a host the user is allowed from.`;
  }
  if (code === 'ECONNREFUSED' || /ECONNREFUSED/i.test(msg)) {
    return `${msg} — nothing is listening on that host:port. MySQL is stopped, it listens on a different port (default 3306), or a firewall blocks it. Test with: Test-NetConnection <host> -Port 3306 (PowerShell) or: nc -vz <host> 3306.`;
  }
  if (code === 'ENOTFOUND' || /ENOTFOUND|getaddrinfo/i.test(msg)) {
    return `${msg} — the host name could not be resolved. If the app runs on the same machine as MySQL, use "localhost" or "127.0.0.1"; in Docker/WSL use the host's LAN IP or host.docker.internal.`;
  }
  if (code === 'ETIMEDOUT' || /timeout/i.test(msg)) {
    return `${msg} — no reply within 15s. The host may be unreachable, the port blocked, or MySQL is starting up.`;
  }
  if (code === 'PROTOCOL_CONNECTION_LOST' || /connection lost/i.test(msg)) {
    return `${msg} — the server closed the connection during the handshake. Usually the port is not MySQL at all (e.g. you pointed at a Postgres or web port), or the server requires SSL — try enabling SSL for the connector.`;
  }
  if (code === 'ER_NOT_SUPPORTED_AUTH_MODE' || /caching_sha2_password|auth plugin/i.test(msg)) {
    return `${msg} — the MySQL user uses an auth plugin this client cannot do (usually caching_sha2_password over a non-TLS connection). Either enable SSL for the connector, or change the user: ALTER USER 'user'@'%' IDENTIFIED WITH mysql_native_password BY '…';`;
  }
  return msg;
}

/** Step-by-step network diagnosis, without attempting a login. */
export async function diagnoseMysql(cfg: MysqlConfig): Promise<{
  dns: { ok: boolean; address?: string; error?: string };
  tcp: { ok: boolean; error?: string };
  hint: string;
}> {
  let dnsResult: { ok: boolean; address?: string; error?: string } = { ok: false };
  try {
    const addrs = await dns.lookup(cfg.host);
    dnsResult = { ok: true, address: addrs.address };
  } catch (err) {
    dnsResult = { ok: false, error: err instanceof Error ? err.message : String(err) };
    return {
      dns: dnsResult,
      tcp: { ok: false, error: 'Skipped — DNS failed' },
      hint: `Host "${cfg.host}" does not resolve from where the app is running. If the app runs on the same machine as MySQL, use "localhost" or "127.0.0.1". If it runs in Docker/WSL, use the host's LAN IP or host.docker.internal.`,
    };
  }
  const tcp: { ok: boolean; error?: string } = await new Promise((resolve) => {
    const socket = new net.Socket();
    const timer = setTimeout(() => { socket.destroy(); resolve({ ok: false, error: 'Timed out after 5s — port is filtered or the host is unreachable' }); }, 5000);
    socket.once('error', (err) => { clearTimeout(timer); resolve({ ok: false, error: err.message }); });
    socket.once('connect', () => { clearTimeout(timer); socket.destroy(); resolve({ ok: true }); });
    socket.connect(cfg.port, cfg.host);
  });
  if (!tcp.ok) {
    return {
      dns: dnsResult,
      tcp,
      hint: `Could not open TCP ${cfg.host}:${cfg.port} (${tcp.error}). MySQL is not listening there — check that mysqld is running, that bind-address allows this host, and that port ${cfg.port} is open in the firewall. Test from PowerShell: Test-NetConnection ${cfg.host} -Port ${cfg.port}`,
    };
  }
  return {
    dns: dnsResult,
    tcp,
    hint: `DNS and TCP ${cfg.host}:${cfg.port} both work, so the network path is fine — the failure is at login. Check the username/password, the database name, and that the MySQL user may connect from this host (see the access-denied note).`,
  };
}

export async function testMysqlConnection(cfg: MysqlConfig): Promise<{
  ok: boolean;
  version?: string;
  database?: string;
  error?: string;
}> {
  let pool: mysql.Pool | null = null;
  try {
    pool = mysql.createPool(toPoolConfig(cfg));
    const [rows] = await pool.query<mysql.RowDataPacket[]>('SELECT VERSION() AS version, DATABASE() AS db');
    return { ok: true, version: String(rows[0]?.version ?? ''), database: String(rows[0]?.db ?? cfg.database) };
  } catch (err) {
    return { ok: false, error: explainMysqlError(err) };
  } finally {
    await pool?.end().catch(() => undefined);
  }
}

const COLUMNS_SQL = `
SELECT
  TABLE_NAME AS \`table\`, COLUMN_NAME AS name, ORDINAL_POSITION AS ordinal,
  DATA_TYPE AS dataType, COLUMN_TYPE AS columnType,
  CHARACTER_MAXIMUM_LENGTH AS maxLength,
  NUMERIC_PRECISION AS numericPrecision, NUMERIC_SCALE AS numericScale,
  DATETIME_PRECISION AS datetimePrecision,
  CASE WHEN IS_NULLABLE = 'YES' THEN 1 ELSE 0 END AS isNullable,
  CASE WHEN EXTRA LIKE '%auto_increment%' THEN 1 ELSE 0 END AS isIdentity,
  COLUMN_DEFAULT AS defaultValue, COLLATION_NAME AS collation
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = ? AND TABLE_NAME IN (
  SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
  WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE'
)
ORDER BY TABLE_NAME, ORDINAL_POSITION;
`;

const PK_SQL = `
SELECT TABLE_NAME AS \`table\`, COLUMN_NAME AS \`column\`
FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA = ? AND CONSTRAINT_NAME = 'PRIMARY'
ORDER BY TABLE_NAME, ORDINAL_POSITION;
`;

const FK_SQL = `
SELECT
  kcu.CONSTRAINT_NAME AS fkName,
  kcu.TABLE_NAME AS \`table\`, kcu.COLUMN_NAME AS \`column\`,
  kcu.REFERENCED_TABLE_NAME AS refTable, kcu.REFERENCED_COLUMN_NAME AS refColumn,
  rc.DELETE_RULE AS onDelete, rc.UPDATE_RULE AS onUpdate
FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu
JOIN INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS rc
  ON rc.CONSTRAINT_SCHEMA = kcu.CONSTRAINT_SCHEMA
 AND rc.CONSTRAINT_NAME = kcu.CONSTRAINT_NAME
WHERE kcu.TABLE_SCHEMA = ? AND kcu.REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY kcu.CONSTRAINT_NAME, kcu.ORDINAL_POSITION;
`;

const INDEX_SQL = `
SELECT
  TABLE_NAME AS \`table\`, INDEX_NAME AS indexName,
  CASE WHEN NON_UNIQUE = 0 THEN 1 ELSE 0 END AS isUnique,
  CASE WHEN INDEX_NAME = 'PRIMARY' THEN 1 ELSE 0 END AS isPrimaryKey,
  COLUMN_NAME AS \`column\`, SEQ_IN_INDEX AS ord
FROM INFORMATION_SCHEMA.STATISTICS
WHERE TABLE_SCHEMA = ? AND INDEX_NAME IS NOT NULL
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;
`;

const VIEWS_SQL = `
SELECT TABLE_NAME AS name, VIEW_DEFINITION AS definition
FROM INFORMATION_SCHEMA.VIEWS
WHERE TABLE_SCHEMA = ?
ORDER BY TABLE_NAME;
`;

const TABLES_SQL = `
SELECT TABLE_NAME AS name
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_NAME;
`;

export async function introspectMysqlSchema(cfg: MysqlConfig): Promise<DatabaseSchema> {
  const pool = mysql.createPool(toPoolConfig(cfg));
  try {
    const [cols] = await pool.query<mysql.RowDataPacket[]>(COLUMNS_SQL, [cfg.database, cfg.database]);
    const [pks] = await pool.query<mysql.RowDataPacket[]>(PK_SQL, [cfg.database]);
    const [fks] = await pool.query<mysql.RowDataPacket[]>(FK_SQL, [cfg.database]);
    const [idxs] = await pool.query<mysql.RowDataPacket[]>(INDEX_SQL, [cfg.database]);
    const [views] = await pool.query<mysql.RowDataPacket[]>(VIEWS_SQL, [cfg.database]);
    const [tables] = await pool.query<mysql.RowDataPacket[]>(TABLES_SQL, [cfg.database]);

    const tablesMap = new Map<string, TableInfo>();
    for (const t of tables as Record<string, unknown>[]) {
      tablesMap.set(String(t.name), {
        schema: 'public',
        name: String(t.name),
        columns: [],
        primaryKey: [],
        foreignKeys: [],
        indexes: [],
        rowCount: 0,
      });
    }
    for (const c of cols as Record<string, unknown>[]) {
      const t = tablesMap.get(String(c.table));
      if (!t) continue;
      const col: ColumnInfo = {
        schema: 'public',
        table: String(c.table),
        name: String(c.name),
        ordinal: Number(c.ordinal),
        dataType: String(c.dataType),
        maxLength: c.maxLength == null ? null : Number(c.maxLength),
        numericPrecision: c.numericPrecision == null ? null : Number(c.numericPrecision),
        numericScale: c.numericScale == null ? null : Number(c.numericScale),
        datetimePrecision: c.datetimePrecision == null ? null : Number(c.datetimePrecision),
        isNullable: Boolean(c.isNullable),
        isIdentity: Boolean(c.isIdentity),
        defaultValue: c.defaultValue == null ? null : String(c.defaultValue),
        collation: c.collation == null ? null : String(c.collation),
        // COLUMN_TYPE carries what DATA_TYPE drops: tinyint(1) vs
        // tinyint, int unsigned, enum('a','b'), bit(1). The MySQL
        // type mapper needs it (see type-map.ts).
        sourceExtra: c.columnType == null ? null : String(c.columnType),
      };
      t.columns.push(col);
    }
    for (const r of pks as Record<string, unknown>[]) {
      tablesMap.get(String(r.table))?.primaryKey.push(String(r.column));
    }
    for (const r of fks as Record<string, unknown>[]) {
      tablesMap.get(String(r.table))?.foreignKeys.push({
        name: String(r.fkName),
        column: String(r.column),
        referencedSchema: 'public',
        referencedTable: String(r.refTable),
        referencedColumn: String(r.refColumn),
        onDelete: String(r.onDelete),
        onUpdate: String(r.onUpdate),
      });
    }
    const indexMap = new Map<string, { name: string; isUnique: boolean; isPrimaryKey: boolean; columns: string[] }>();
    for (const r of idxs as Record<string, unknown>[]) {
      const k = `${String(r.table)}.${String(r.indexName)}`;
      if (!indexMap.has(k)) {
        const info = {
          name: String(r.indexName),
          isUnique: Boolean(r.isUnique),
          isPrimaryKey: Boolean(r.isPrimaryKey),
          columns: [],
        };
        indexMap.set(k, info);
        // The PRIMARY key index is the PK itself, not a separate index.
        if (!info.isPrimaryKey) tablesMap.get(String(r.table))?.indexes.push(info);
      }
      indexMap.get(k)!.columns.push(String(r.column));
    }
    // Exact row counts (TABLE_ROWS is only an InnoDB estimate and
    // would make validation report false mismatches).
    await Promise.all(
      [...tablesMap.values()].map(async (t) => {
        const [rows] = await pool.query<mysql.RowDataPacket[]>(
          `SELECT COUNT(*) AS n FROM \`${t.name.replace(/`/g, '``')}\``,
        );
        t.rowCount = Number((rows[0] as Record<string, unknown>)?.n ?? 0);
      }),
    );
    return {
      database: cfg.database,
      tables: [...tablesMap.values()],
      views: (views as Record<string, unknown>[]).map((v) => ({
        schema: 'public',
        name: String(v.name),
        definition: String(v.definition ?? ''),
      })),
    };
  } finally {
    await pool.end().catch(() => undefined);
  }
}

/** Stream one table's rows in batches for the data-copy phase. */
export async function streamMysqlTableRows(
  cfg: MysqlConfig,
  schema: string,
  table: string,
  batchSize: number,
  onBatch: (rows: Record<string, unknown>[]) => Promise<void>,
): Promise<number> {
  // Backtick-quoted identifiers only; schema/table come from the
  // introspected list, never raw user input, and are validated here.
  if (!/^[A-Za-z0-9_]+$/.test(schema) || !/^[A-Za-z0-9_ \-]+$/.test(table)) {
    throw new Error(`Unsafe table name: ${schema}.${table}`);
  }
  const safeTable = table.replace(/`/g, '``');
  let total = 0;
  const pool = mysql.createPool(toPoolConfig(cfg));
  try {
    const [countRows] = await pool.query<mysql.RowDataPacket[]>(
      `SELECT COUNT(*) AS n FROM \`${safeTable}\``,
    );
    const totalRows = Number((countRows[0] as Record<string, unknown>)?.n ?? 0);
    for (let offset = 0; offset < totalRows; offset += batchSize) {
      const [rows] = await pool.query<mysql.RowDataPacket[]>(
        `SELECT * FROM \`${safeTable}\` LIMIT ?, ?`,
        [offset, batchSize],
      );
      const batch = rows as unknown as Record<string, unknown>[];
      if (batch.length === 0) break;
      await onBatch(batch);
      total += batch.length;
    }
  } finally {
    await pool.end().catch(() => undefined);
  }
  return total;
}
