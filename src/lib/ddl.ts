import type { ColumnInfo, TableInfo, ViewInfo } from './sqlserver';
import { mapSqlServerType } from './type-map';

/** User overrides from Step 4: key = "schema.table.column", value = Postgres type. */
export type TypeOverrides = Record<string, string>;

export function pgIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

/** Map a SQL Server schema name to a Postgres schema. `dbo` (the usual
 *  default) becomes `public`, the NHost/Hasura default schema. */
export function pgSchema(schema: string): string {
  return schema.toLowerCase() === 'dbo' ? 'public' : schema.toLowerCase();
}

function pgTypeFor(col: ColumnInfo, overrides: TypeOverrides): string {
  const key = `${col.schema}.${col.table}.${col.name}`;
  if (overrides[key]) return overrides[key];
  return mapSqlServerType({
    dataType: col.dataType,
    maxLength: col.maxLength,
    numericPrecision: col.numericPrecision,
    numericScale: col.numericScale,
    datetimePrecision: col.datetimePrecision,
  }).pgType;
}

/** Convert a SQL Server DEFAULT expression to a Postgres one.
 *  Returns null when the default cannot be translated (column is created
 *  without a default and the loss is reported in the migration log). */
export function convertDefault(sqlServerDefault: string | null): string | null {
  if (!sqlServerDefault) return null;
  let d = sqlServerDefault.trim();
  // Strip the outer parens SQL Server stores, e.g. ((0)) -> 0
  while (d.startsWith('(') && d.endsWith(')')) d = d.slice(1, -1).trim();
  const upper = d.toUpperCase();
  // All SQL Server "current date/time" functions -> Postgres now().
  // SYSUTCDATETIME() was missing here (it was only handled in views),
  // so a column DEFAULT (SYSUTCDATETIME()) was emitted verbatim and
  // Postgres failed the whole CREATE TABLE with
  // "function sysutcdatetime() does not exist".
  if (
    upper === 'GETDATE()' ||
    upper === 'SYSDATETIME()' ||
    upper === 'SYSUTCDATETIME()' ||
    upper === 'GETUTCDATE()' ||
    upper === 'SYSDATETIMEOFFSET()' ||
    upper === 'CURRENT_TIMESTAMP'
  ) {
    return 'now()';
  }
  if (upper === 'NEWID()' || upper === 'NEWSEQUENTIALID()') return 'gen_random_uuid()';
  if (/^N'/.test(d)) return `'${d.slice(2)}`; // N'...' -> '...'
  if (upper === 'NULL') return null;
  // An unknown function call (e.g. USER_NAME(), HOST_NAME()) would fail
  // in Postgres the same way SYSUTCDATETIME() did. Drop the default
  // rather than aborting the whole migration on it.
  if (/^[A-Z_][A-Z0-9_]*\s*\(.*\)$/i.test(d)) return null;
  return d; // literals (0, 1, 'x') pass through unchanged
}

export function generateCreateTable(table: TableInfo, overrides: TypeOverrides): string {
  const schema = pgSchema(table.schema);
  const lines: string[] = [];
  lines.push(`CREATE TABLE IF NOT EXISTS ${pgIdent(schema)}.${pgIdent(table.name)} (`);
  const defs: string[] = table.columns.map((col) => {
    const parts = [pgIdent(col.name), pgTypeFor(col, overrides)];
    if (col.isIdentity) parts.push('GENERATED BY DEFAULT AS IDENTITY');
    if (!col.isNullable) parts.push('NOT NULL');
    const def = convertDefault(col.defaultValue);
    if (def !== null) parts.push(`DEFAULT ${def}`);
    return `  ${parts.join(' ')}`;
  });
  if (table.primaryKey.length > 0) {
    defs.push(
      `  PRIMARY KEY (${table.primaryKey.map(pgIdent).join(', ')})`,
    );
  }
  lines.push(defs.join(',\n'));
  lines.push(');');
  return lines.join('\n');
}

export function generateForeignKeys(table: TableInfo): string[] {
  const schema = pgSchema(table.schema);
  const seen = new Set<string>();
  const out: string[] = [];
  for (const fk of table.foreignKeys) {
    if (seen.has(fk.name)) continue; // one statement per multi-column FK
    seen.add(fk.name);
    const cols = table.foreignKeys
      .filter((f) => f.name === fk.name)
      .map((f) => f.column);
    const refCols = table.foreignKeys
      .filter((f) => f.name === fk.name)
      .map((f) => f.referencedColumn);
    const onDelete =
      fk.onDelete === 'NO_ACTION' ? '' : ` ON DELETE ${fk.onDelete.replace(/_/g, ' ')}`;
    const onUpdate =
      fk.onUpdate === 'NO_ACTION' ? '' : ` ON UPDATE ${fk.onUpdate.replace(/_/g, ' ')}`;
    out.push(
      `ALTER TABLE ${pgIdent(schema)}.${pgIdent(table.name)} ` +
        `ADD CONSTRAINT ${pgIdent(fk.name)} FOREIGN KEY (${cols.map(pgIdent).join(', ')}) ` +
        `REFERENCES ${pgIdent(pgSchema(fk.referencedSchema))}.${pgIdent(fk.referencedTable)} ` +
        `(${refCols.map(pgIdent).join(', ')})${onDelete}${onUpdate};`,
    );
  }
  return out;
}

export function generateIndexes(table: TableInfo): string[] {
  const schema = pgSchema(table.schema);
  return table.indexes.map((idx) => {
    const unique = idx.isUnique ? 'UNIQUE ' : '';
    return (
      `CREATE ${unique}INDEX IF NOT EXISTS ${pgIdent(idx.name)} ` +
      `ON ${pgIdent(schema)}.${pgIdent(table.name)} (${idx.columns.map(pgIdent).join(', ')});`
    );
  });
}

// ── T-SQL -> Postgres view conversion ──────────────────────────────────

/** Convert a T-SQL view body to Postgres SQL. Best-effort, rule-based:
 *  covers the common constructs; anything exotic is flagged for review
 *  and the original is kept in a comment. */
export function convertViewSql(definition: string): { sql: string; notes: string[] } {
  const notes: string[] = [];
  let sql = definition;

  // 1. Drop the CREATE VIEW header — the caller re-adds it with the
  //    Postgres schema name. Keep everything from the first SELECT.
  const selectIdx = sql.search(/\bSELECT\b/i);
  if (selectIdx > 0) sql = sql.slice(selectIdx);
  else notes.push('Could not find SELECT in view definition; review manually.');

  // 2. Square brackets -> double quotes: [dbo].[Orders] -> "dbo"."Orders"
  sql = sql.replace(/\[([^\]]+)\]/g, '"$1"');

  // 3. dbo. prefix -> public. (other schemas are lower-cased as-is)
  sql = sql.replace(/"dbo"\./gi, '"public".');

  // 4. TOP n -> LIMIT n (only the common `SELECT TOP n ...` form, and
  //    `SELECT DISTINCT TOP n`). TOP with PERCENT / WITH TIES is flagged.
  if (/TOP\s+\d+\s+PERCENT/i.test(sql) || /WITH\s+TIES/i.test(sql)) {
    notes.push('TOP … PERCENT / WITH TIES is not supported in Postgres; rewrite manually.');
  }
  sql = sql.replace(
    /\bSELECT\s+(DISTINCT\s+)?TOP\s+(\d+)\s+/i,
    (_m, distinct: string | undefined, n: string) =>
      `SELECT ${distinct ?? ''}`,
  );
  const topMatch = definition.match(/\bTOP\s+(\d+)/i);
  // LIMIT is appended at the end (after ORDER BY) below.
  const limit = topMatch && !/PERCENT/i.test(definition) ? Number(topMatch[1]) : null;

  // 5. Date / null functions
  sql = sql.replace(/\bGETDATE\s*\(\s*\)/gi, 'now()');
  sql = sql.replace(/\bSYSUTCDATETIME\s*\(\s*\)/gi, 'now()');
  sql = sql.replace(/\bSYSDATETIME\s*\(\s*\)/gi, 'now()');
  sql = sql.replace(/\bSYSDATETIMEOFFSET\s*\(\s*\)/gi, 'now()');
  sql = sql.replace(/\bGETUTCDATE\s*\(\s*\)/gi, "now() AT TIME ZONE 'UTC'");
  sql = sql.replace(/\bNEWID\s*\(\s*\)/gi, 'gen_random_uuid()');
  sql = sql.replace(/\bNEWSEQUENTIALID\s*\(\s*\)/gi, 'gen_random_uuid()');
  sql = sql.replace(/\bLEN\s*\(/gi, 'LENGTH(');
  sql = sql.replace(/\bCHARINDEX\s*\(/gi, 'STRPOS(');

  // 6. String concatenation: + -> ||, but only between string-ish
  //    operands is unsafe to detect statically, so flag it for review
  //    when a + appears outside arithmetic-looking contexts.
  if (/\+/.test(sql)) {
    notes.push('Review "+" operators: in T-SQL + concatenates strings, in Postgres use ||. Numeric + is unchanged.');
  }
  // N'...' string literals -> '...'
  sql = sql.replace(/\bN'([^']*)'/g, "'$1'");

  // 7. Trailing semicolon / GO batch separators
  sql = sql.replace(/^\s*GO\s*$/gim, '').trim();
  sql = sql.replace(/;\s*$/, '');

  if (limit !== null) sql += `\nLIMIT ${limit}`;

  return { sql, notes };
}

export function generateCreateView(
  view: ViewInfo,
): { sql: string; notes: string[] } {
  const { sql, notes } = convertViewSql(view.definition);
  const header = `CREATE OR REPLACE VIEW ${pgIdent(pgSchema(view.schema))}.${pgIdent(view.name)} AS`;
  return { sql: `${header}\n${sql};`, notes };
}

/** Full script, in dependency-safe order:
 *  1. tables (no FKs)  2. FKs  3. indexes  4. views. */
export function generateMigrationScript(
  tables: TableInfo[],
  views: ViewInfo[],
  overrides: TypeOverrides,
): { script: string; viewNotes: Record<string, string[]> } {
  const parts: string[] = [
    '-- Generated by sqlserver-to-nhost-migrator',
    '-- Review before running against production. Views are converted',
    '-- from T-SQL with best-effort rules; check the notes below.',
    '',
  ];
  const viewNotes: Record<string, string[]> = {};

  for (const t of tables) parts.push(generateCreateTable(t, overrides), '');
  for (const t of tables) {
    for (const fk of generateForeignKeys(t)) parts.push(fk);
  }
  if (tables.some((t) => t.foreignKeys.length)) parts.push('');
  for (const t of tables) {
    for (const ix of generateIndexes(t)) parts.push(ix);
  }
  if (tables.some((t) => t.indexes.length)) parts.push('');

  for (const v of views) {
    const { sql, notes } = generateCreateView(v);
    if (notes.length) viewNotes[`${v.schema}.${v.name}`] = notes;
    parts.push(`-- View: ${v.schema}.${v.name}`);
    for (const n of notes) parts.push(`--   NOTE: ${n}`);
    parts.push(sql, '');
  }

  return { script: parts.join('\n'), viewNotes };
}

/** Statements in execution order for the live migration (views last,
 *  because they may reference the migrated tables). */
export function schemaStatements(
  tables: TableInfo[],
  views: ViewInfo[],
  overrides: TypeOverrides,
): { tables: string[]; fks: string[]; indexes: string[]; views: { name: string; sql: string; notes: string[] }[] } {
  return {
    tables: tables.map((t) => generateCreateTable(t, overrides)),
    fks: tables.flatMap((t) => generateForeignKeys(t)),
    indexes: tables.flatMap((t) => generateIndexes(t)),
    views: views.map((v) => {
      const { sql, notes } = generateCreateView(v);
      return { name: `${v.schema}.${v.name}`, sql, notes };
    }),
  };
}
