/** Find `NAME(...)` calls with balanced parens and rewrite them.
 *  `rewrite` gets the top-level comma-separated arguments and returns
 *  the replacement, or null to leave the call unchanged. String
 *  literals (with '' escapes) are respected while scanning. */
function rewriteCalls(sql: string, name: string, rewrite: (args: string[]) => string | null): string {
  const re = new RegExp(`\\b${name}\\s*\\(`, 'gi');
  let out = '';
  let i = 0;
  while (i < sql.length) {
    const m = re.exec(sql.slice(i));
    if (!m) { out += sql.slice(i); break; }
    const start = i + m.index;
    out += sql.slice(i, start);
    // Find the matching close paren, tracking nesting and quotes.
    let depth = 0, j = start + m[0].length - 1, inStr = false;
    for (; j < sql.length; j++) {
      const c = sql[j];
      if (c === "'") inStr = !inStr;
      if (inStr) continue;
      if (c === '(') depth++;
      else if (c === ')') { depth--; if (depth === 0) break; }
    }
    if (j >= sql.length) { out += sql.slice(start); break; }
    const inner = sql.slice(start + m[0].length, j);
    // Split inner on top-level commas.
    const parts: string[] = [];
    let cur = '', d = 0, s = false;
    for (const c of inner) {
      if (c === "'") s = !s;
      if (!s) {
        if (c === '(') d++;
        else if (c === ')') d--;
        else if (c === ',' && d === 0) { parts.push(cur); cur = ''; continue; }
      }
      cur += c;
    }
    parts.push(cur);
    const replacement = rewrite(parts.map((p) => p.trim()));
    out += replacement ?? sql.slice(start, j + 1);
    i = j + 1;
  }
  return out;
}

/** Rewrite CONVERT(type, expr [, style]) as CAST(expr AS type).
 *  Parses balanced parentheses and splits on top-level commas, so
 *  CONVERT(varchar(10), x, 101) and CONVERT(datetime, GETDATE()) work.
 *  A style argument (the 3rd) is dropped — Postgres has no equivalent;
 *  date formatting must be done with TO_CHAR instead. */
function convertConvertCalls(sql: string, notes: string[]): string {
  const mapType = (t: string): string => {
    const tt = t.trim().toLowerCase();
    if (tt.startsWith('nvarchar') || tt.startsWith('nchar')) return tt.replace(/^n(var)?char/, 'varchar');
    if (tt === 'datetime' || tt === 'datetime2' || tt === 'smalldatetime') return 'timestamptz';
    if (tt === 'bit') return 'boolean';
    if (tt === 'int') return 'integer';
    if (tt === 'uniqueidentifier') return 'uuid';
    if (tt === 'float') return 'double precision';
    return tt;
  };
  return rewriteCalls(sql, 'CONVERT', (parts) => {
    if (parts.length >= 2) {
      if (parts.length > 2) notes.push('CONVERT with a style argument was rewritten as CAST — date formatting may differ; use TO_CHAR if the output format matters.');
      return `CAST(${parts[1]} AS ${mapType(parts[0])})`;
    }
    notes.push('Unparseable CONVERT call left unchanged; review manually.');
    return null;
  });
}

/** Strip T-SQL table hints (`WITH (NOLOCK)`, `WITH (NOLOCK, INDEX(…))`,
 *  …) with balanced-paren scanning, so nested parens inside the hint
 *  do not leave a stray `)` behind. A leading CTE `WITH x AS (` is
 *  not a hint (it is followed by an identifier and AS, not `(`) and
 *  is left alone. */
function stripTableHints(sql: string): string {
  const HINT = /^(?:NOLOCK|READUNCOMMITTED|READPAST|REPEATABLEREAD|SERIALIZABLE|ROWLOCK|UPDLOCK|HOLDLOCK|TABLOCK|INDEX\b)/i;
  let out = '';
  let i = 0;
  while (i < sql.length) {
    const m = /\bWITH\s*\(/i.exec(sql.slice(i));
    if (!m) { out += sql.slice(i); break; }
    const start = i + m.index;
    const innerStart = start + m[0].length;
    const inner = sql.slice(innerStart, innerStart + 40);
    if (!HINT.test(inner.trim())) { out += sql.slice(i, innerStart); i = innerStart; continue; }
    // Find the matching close paren, tracking nesting and quotes.
    let depth = 1, j = innerStart, inStr = false;
    for (; j < sql.length; j++) {
      const c = sql[j];
      if (c === "'") inStr = !inStr;
      if (inStr) continue;
      if (c === '(') depth++;
      else if (c === ')') { depth--; if (depth === 0) break; }
    }
    if (j >= sql.length) { out += sql.slice(i); break; }
    out += sql.slice(i, start);
    i = j + 1;
  }
  return out;
}

/** Convert a view body to Postgres SQL. Best-effort, rule-based:
 *  covers the common constructs; anything exotic is flagged for review
 *  and the original is kept in a comment.
 *  `knownNames` are the exact (mixed-case) table and view names in the
 *  migration, and `knownColumns` the exact column names — Postgres
 *  folds unquoted identifiers to lowercase, but the tables and columns
 *  were created quoted ("CommunityMethod2", "WorkerId"), so a view
 *  reference must be quoted with its exact case or it fails with
 *  relation "public.communitymethod2" does not exist / column
 *  cm2.workerid does not exist.
 *  `dialect` selects the source dialect: 'tsql' (SQL Server, the
 *  default), 'mysql', 'postgres' (already Postgres — only the
 *  schema/table quoting steps run), 'oracle' or 'sqlite'.
 *  `database` is the MySQL database name, or the Oracle owner, used
 *  to turn `mydb`.`table` / `OWNER`.`table` references into
 *  `"public"."table"`. */
export function convertViewSql(definition: string, knownNames: string[] = [], knownColumns: string[] = [], dialect: 'tsql' | 'mysql' | 'postgres' | 'oracle' | 'sqlite' = 'tsql', database = ''): { sql: string; notes: string[] } {
  const notes: string[] = [];
  let sql = definition;
  const known = new Map(knownNames.map((n) => [n.toLowerCase(), n]));
  const knownCols = new Map(knownColumns.map((n) => [n.toLowerCase(), n]));
  const isMysql = dialect === 'mysql';
  const isTsql = dialect === 'tsql';
  const isOracle = dialect === 'oracle';
  const isSqlite = dialect === 'sqlite';
  const isPostgres = dialect === 'postgres';

  // 1. Drop the CREATE VIEW header — the caller re-adds it with the
  //    Postgres schema name. Keep everything from the first SELECT,
  //    or from a leading WITH … AS ( … ) CTE if one comes first:
  //    slicing from SELECT on a CTE view dropped the `WITH x AS (`
  //    header and left a stray `)` behind ("syntax error at or near )").
  const cteIdx = sql.search(/\bWITH\s+[A-Za-z_][A-Za-z0-9_$#]*\s+AS\s*\(/i);
  const selectIdx = sql.search(/\bSELECT\b/i);
  if (cteIdx >= 0 && (selectIdx === -1 || cteIdx < selectIdx)) sql = sql.slice(cteIdx);
  else if (selectIdx > 0) sql = sql.slice(selectIdx);
  else if (selectIdx === -1) notes.push('Could not find SELECT in view definition; review manually.');

  // 2. Square brackets (T-SQL) or backticks (MySQL) -> double quotes:
  // [dbo].[Orders] -> "dbo"."Orders"; `mydb`.`orders` -> "mydb"."orders"
  // Postgres definitions (pg_get_viewdef) are already quoted properly.
  if (!isPostgres) {
    sql = isMysql
      ? sql.replace(/`([^`]+)`/g, '"$1"')
      : sql.replace(/\[([^\]]+)\]/g, '"$1"');
  }

  // 2b. Table hints (T-SQL only): WITH (NOLOCK) / WITH (READUNCOMMITTED)
  // / WITH (INDEX(...)). Postgres has no table hints — `FROM
  // dbo.CallLog CL WITH (NOLOCK)` fails with "syntax error at or near
  // CL" / "WITH". Strip them, including the bare `(NOLOCK)` form (no
  // WITH keyword) and hints with nested parens such as
  // WITH (NOLOCK, INDEX(IX_Foo)).
  // (A leading WITH … AS ( … ) CTE is not a hint and is left alone:
  // hints only appear after a table name / alias.)
  if (isTsql) {
    sql = stripTableHints(sql);
    sql = sql.replace(/\s*\(\s*(?:NOLOCK|READUNCOMMITTED|READPAST)\s*\)/gi, '');
  }

  // 3. Schema / database prefix -> public. T-SQL: both quoted "dbo".
  // and unquoted dbo. — the unquoted form was missed before, so views
  // failed with relation "dbo.communitymethod2" does not exist. Same
  // for dbhkuser. MySQL: the database name (`mydb`. / mydb.) maps to
  // public the same way the tables do. Oracle: `database` is the owner
  // name. Postgres / SQLite views carry no prefix to rewrite.
  if (isMysql) {
    if (database) {
      const db = database.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      sql = sql.replace(new RegExp(`"${db}"\\.`, 'gi'), '"public".');
      sql = sql.replace(new RegExp(`\\b${db}\\.`, 'gi'), '"public".');
    }
  } else if (isOracle) {
    if (database) {
      const owner = database.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      sql = sql.replace(new RegExp(`"${owner}"\\.`, 'gi'), '"public".');
      sql = sql.replace(new RegExp(`\\b${owner}\\.`, 'gi'), '"public".');
    }
  } else if (isTsql) {
    sql = sql.replace(/"dbo"\./gi, '"public".');
    sql = sql.replace(/\bdbo\./gi, '"public".');
    sql = sql.replace(/"dbhkuser"\./gi, '"public".');
    sql = sql.replace(/\bdbhkuser\./gi, '"public".');
  }

  // 3b. Quote the table name after a schema prefix, with its exact
  // case from the known tables/views when available. Without this,
  // `"public".CommunityMethod2` folds to `public.communitymethod2`,
  // which does not exist — the table is "CommunityMethod2".
  // Bare FROM/JOIN references to a known table are qualified the same
  // way, unless the name is a CTE defined in this view.
  if (known.size > 0) {
    sql = sql.replace(/"public"\.("?)([A-Za-z_][A-Za-z0-9_$#]*)("?)/g, (_m, _q1, name: string) => {
      const exact = known.get(name.toLowerCase());
      return `"public"."${exact ?? name}"`;
    });
    const cteNames = new Set<string>();
    for (const m of sql.matchAll(/\bWITH\s+([A-Za-z_][A-Za-z0-9_$#]*)\s+AS\s*\(/gi)) cteNames.add(m[1].toLowerCase());
    for (const m of sql.matchAll(/,\s*([A-Za-z_][A-Za-z0-9_$#]*)\s+AS\s*\(/g)) cteNames.add(m[1].toLowerCase());
    sql = sql.replace(/\b(FROM|JOIN)\s+([A-Za-z_][A-Za-z0-9_$#]*)/gi, (m, kw: string, name: string) => {
      if (cteNames.has(name.toLowerCase())) return m;
      const exact = known.get(name.toLowerCase());
      return exact ? `${kw} "public"."${exact}"` : m;
    });
  }

  // 3c. Quote qualified column references with their exact case:
  // `cm2.WorkerId` and `CommunityMethod1.WorkerId` fold to
  // `cm2.workerid` / `communitymethod1.workerid`, which do not exist
  // — the column is "WorkerId". The qualifier is quoted only when it
  // is a known table name; a table alias (cm2, CL) is left unquoted,
  // because quoting an alias as written ("CL") would NOT match the
  // alias as defined (unquoted CL folds to cl). String literals are
  // left untouched (the literal branch of the alternation consumes
  // them first, so 'cm2.workerid' inside quotes is never rewritten).
  if (knownCols.size > 0) {
    sql = sql.replace(/'(?:[^']|'')*'|(?<![\w"'.])([A-Za-z_][A-Za-z0-9_$#]*)\.([A-Za-z_][A-Za-z0-9_$#]*)/g,
      (m, qualifier: string | undefined, col: string | undefined) => {
        if (qualifier === undefined || col === undefined) return m; // string literal
        const exactCol = knownCols.get(col.toLowerCase());
        if (!exactCol) return m;
        const exactTable = known.get(qualifier.toLowerCase());
        const qOut = exactTable ? `"${exactTable}"` : qualifier;
        return `${qOut}."${exactCol}"`;
      });
  }

  // 4. TOP n -> LIMIT n (T-SQL only; MySQL already uses LIMIT).
  // Only the common `SELECT TOP n ...` form, and `SELECT DISTINCT
  // TOP n`. TOP with PERCENT / WITH TIES is flagged.
  let limit: number | null = null;
  if (isTsql) {
    if (/TOP\s+\d+\s+PERCENT/i.test(sql) || /WITH\s+TIES/i.test(sql)) {
      notes.push('TOP … PERCENT / WITH TIES is not supported in Postgres; rewrite manually.');
    }
    sql = sql.replace(
      /\bSELECT\s+(DISTINCT\s+)?TOP\s+(\d+)\s+/i,
      (_m, distinct: string | undefined, n: string) =>
        `SELECT ${distinct ?? ''}`,
    );
    const topMatch = definition.match(/\bTOP\s+(\d+)/i);
    // LIMIT is appended at the end (after ORDER BY) below.
    limit = topMatch && !/PERCENT/i.test(definition) ? Number(topMatch[1]) : null;
  }

  // 5. Date / null functions
  if (isMysql) {
    sql = sql.replace(/\bNOW\s*\(\s*\)/gi, 'now()');
    sql = sql.replace(/\bCURDATE\s*\(\s*\)/gi, 'CURRENT_DATE');
    sql = sql.replace(/\bCURTIME\s*\(\s*\)/gi, 'CURRENT_TIME');
    sql = sql.replace(/\bUNIX_TIMESTAMP\s*\(\s*\)/gi, 'extract(epoch from now())');
    sql = rewriteCalls(sql, 'UNIX_TIMESTAMP', (parts) =>
      parts.length === 1 ? `extract(epoch from ${parts[0]})` : null);
    sql = sql.replace(/\bIFNULL\s*\(/gi, 'COALESCE(');
    // MySQL ISNULL(x) is a boolean test (1 when x is NULL), not a
    // two-argument fallback — unlike T-SQL's ISNULL(a, b).
    sql = rewriteCalls(sql, 'ISNULL', (parts) =>
      parts.length === 1 ? `(${parts[0]} IS NULL)` : null);
    // IF(cond, then, else) -> CASE WHEN cond THEN then ELSE else END.
    // (Postgres has no IF() function; its IF is procedural only.)
    sql = rewriteCalls(sql, 'IF', (parts) =>
      parts.length === 3 ? `(CASE WHEN ${parts[0]} THEN ${parts[1]} ELSE ${parts[2]} END)` : null);
    // DATE_ADD(date, INTERVAL n unit) / DATE_SUB(...) -> date +/- INTERVAL.
    const dateShift = (sign: '+' | '-') => (parts: string[]) => {
      if (parts.length !== 2) return null;
      const m = parts[1].match(/^INTERVAL\s+(\S+)\s+(\w+)$/i);
      if (!m) return null;
      return `(${parts[0]} ${sign} INTERVAL '${m[1]} ${m[2].toLowerCase()}')`;
    };
    sql = rewriteCalls(sql, 'DATE_ADD', dateShift('+'));
    sql = rewriteCalls(sql, 'DATE_SUB', dateShift('-'));
    // LOCATE(substr, str) has the arguments the other way round from
    // Postgres STRPOS(str, substr).
    sql = rewriteCalls(sql, 'LOCATE', (parts) =>
      parts.length === 2 ? `STRPOS(${parts[1]}, ${parts[0]})` : null);
    // UUID() exists in Postgres as gen_random_uuid().
    sql = sql.replace(/\bUUID\s*\(\s*\)/gi, 'gen_random_uuid()');
    // CONCAT() exists in Postgres with the same meaning — leave it.
  } else if (isOracle) {
    // NVL(a, b) is Oracle's two-argument fallback — same as COALESCE.
    sql = sql.replace(/\bNVL\s*\(/gi, 'COALESCE(');
    sql = sql.replace(/\bSYSDATE\b/gi, 'now()');
    sql = sql.replace(/\bSYSTIMESTAMP\b/gi, 'now()');
    // TO_DATE(x [, fmt]) -> CAST(x AS timestamp); the format string
    // is dropped, so a non-ISO date literal may need review.
    sql = rewriteCalls(sql, 'TO_DATE', (parts) => {
      if (parts.length >= 1) {
        if (parts.length > 1) notes.push('TO_DATE with a format string was rewritten as CAST — non-ISO date text may need review.');
        return `CAST(${parts[0]} AS timestamp)`;
      }
      return null;
    });
    // TO_CHAR(x [, fmt]) — Postgres TO_CHAR uses different format
    // codes from Oracle, so a format string is flagged, not rewritten.
    if (/\bTO_CHAR\s*\(/i.test(sql)) notes.push('TO_CHAR format codes differ between Oracle and Postgres — check the output format.');
    // DECODE(a, b, c, ...) -> CASE WHEN a = b THEN c ... END is not
    // attempted — flag it.
    if (/\bDECODE\s*\(/i.test(sql)) notes.push('DECODE was left unchanged — rewrite it as CASE WHEN in Postgres.');
    // ROWNUM has no Postgres equivalent (use LIMIT / row_number()).
    if (/\bROWNUM\b/i.test(sql)) notes.push('ROWNUM was left unchanged — Postgres has no ROWNUM; use LIMIT or row_number() OVER ().');
    // SELECT ... FROM DUAL needs no FROM clause in Postgres.
    sql = sql.replace(/\bFROM\s+DUAL\b/gi, '');
    // Casts: VARCHAR2(n) / NUMBER(p,s) inside CAST(...) -> Postgres types.
    sql = sql.replace(/\bVARCHAR2\s*\(/gi, 'varchar(');
    sql = sql.replace(/\bNVARCHAR2\s*\(/gi, 'varchar(');
    sql = sql.replace(/\bNUMBER\s*\(/gi, 'numeric(');
    // || is already Postgres string concatenation — leave it.
  } else if (isSqlite) {
    sql = sql.replace(/\bdate\s*\(\s*'now'\s*\)/gi, 'CURRENT_DATE');
    sql = sql.replace(/\bdatetime\s*\(\s*'now'\s*\)/gi, 'now()');
    sql = sql.replace(/\btime\s*\(\s*'now'\s*\)/gi, 'CURRENT_TIME');
    // strftime('%Y-%m-%d', x) -> to_char(x, 'YYYY-MM-DD') for the
    // common patterns; anything else is flagged.
    sql = rewriteCalls(sql, 'strftime', (parts) => {
      if (parts.length !== 2) return null;
      const fmt = parts[0].replace(/^'|'$/g, '');
      const pgFmt = fmt
        .replace(/%Y/g, 'YYYY').replace(/%m/g, 'MM').replace(/%d/g, 'DD')
        .replace(/%H/g, 'HH24').replace(/%M/g, 'MI').replace(/%S/g, 'SS');
      if (pgFmt !== fmt && !/%/.test(pgFmt)) return `to_char(${parts[1]}, '${pgFmt}')`;
      notes.push('strftime with an unmapped format was left unchanged — rewrite with to_char.');
      return null;
    });
    // || is already Postgres string concatenation — leave it.
  } else if (isTsql) {
    sql = sql.replace(/\bSYSUTCDATETIME\s*\(\s*\)/gi, 'now()');
    sql = sql.replace(/\bSYSDATETIME\s*\(\s*\)/gi, 'now()');
    sql = sql.replace(/\bSYSDATETIMEOFFSET\s*\(\s*\)/gi, 'now()');
    sql = sql.replace(/\bGETUTCDATE\s*\(\s*\)/gi, "now() AT TIME ZONE 'UTC'");
    sql = sql.replace(/\bNEWID\s*\(\s*\)/gi, 'gen_random_uuid()');
    sql = sql.replace(/\bNEWSEQUENTIALID\s*\(\s*\)/gi, 'gen_random_uuid()');

    // 5b. CONVERT(type, expr [, style]) -> CAST(expr AS type).
    // Balanced-paren parsing: CONVERT(varchar(10), x, 101) has commas
    // inside the type and a style argument, so a plain regex cannot do it.
    sql = convertConvertCalls(sql, notes);
    // varchar(max) / nvarchar(max) -> text (Postgres has no (max)).
    sql = sql.replace(/\b(varchar|nvarchar)\s*\(\s*max\s*\)/gi, 'text');
    // DATEADD(unit, n, date) -> date + INTERVAL 'n unit' for the common units.
    sql = sql.replace(/\bDATEADD\s*\(\s*(day|dd|d|month|mm|m|year|yy|yyyy|hour|hh|minute|mi|n|second|ss|s)\s*,\s*([^,]+?)\s*,\s*([^)]+?)\)/gi,
      (_m, unit: string, n: string, d: string) => {
        const u = { day: 'day', dd: 'day', d: 'day', month: 'month', mm: 'month', m: 'month', year: 'year', yy: 'year', yyyy: 'year', hour: 'hour', hh: 'hour', minute: 'minute', mi: 'minute', n: 'minute', second: 'second', ss: 'second', s: 'second' }[unit.toLowerCase()] ?? 'day';
        return `(${d.trim()} + INTERVAL '${n.trim()} ${u}')`;
      });
    sql = sql.replace(/\bISNULL\s*\(/gi, 'COALESCE(');
    sql = sql.replace(/\bLEN\s*\(/gi, 'LENGTH(');
    sql = sql.replace(/\bCHARINDEX\s*\(/gi, 'STRPOS(');
  }

  // 6. String concatenation (T-SQL only): + -> ||, but only between
  // string-ish operands is unsafe to detect statically, so flag it
  // for review when a + appears outside arithmetic-looking contexts.
  // (MySQL uses CONCAT(), and + there is numeric — no flag needed.
  // Oracle and SQLite already use ||, Postgres needs nothing.)
  if (isTsql && /\+/.test(sql)) {
    notes.push('Review "+" operators: in T-SQL + concatenates strings, in Postgres use ||. Numeric + is unchanged.');
  }
  // N'...' string literals -> '...' (T-SQL only).
  if (isTsql) sql = sql.replace(/\bN'([^']*)'/g, "'$1'");

  // 7. Trailing semicolon / GO batch separators
  sql = sql.replace(/^\s*GO\s*$/gim, '').trim();
  sql = sql.replace(/;\s*$/, '');

  if (limit !== null) sql += `\nLIMIT ${limit}`;

  return { sql, notes };
}

export function generateCreateView(
  view: ViewInfo,
  knownNames: string[] = [],
  knownColumns: string[] = [],
  source: SourceKind = 'sqlserver',
  database = '',
): { sql: string; notes: string[] } {
  const dialect = source === 'mysql' ? 'mysql' : source === 'postgres' ? 'postgres' : source === 'oracle' ? 'oracle' : source === 'sqlite' ? 'sqlite' : 'tsql';
  const { sql, notes } = convertViewSql(view.definition, knownNames, knownColumns, dialect, database);
  const header = `CREATE OR REPLACE VIEW ${pgIdent(pgSchema(view.schema))}.${pgIdent(view.name)} AS`;
  return { sql: `${header}\n${sql};`, notes };
}

/** Full script, in dependency-safe order:
 *  1. tables (no FKs)  2. indexes  3. FKs  4. views.
 *  Indexes come before FKs: a foreign key may reference a column that
 *  is unique only via a UNIQUE index (not a PK), and Postgres requires
 *  that unique index to exist before the FK is created — creating FKs
 *  first failed with "no unique constraint matching given keys for
 *  referenced table CallLog" in the 2026-11-22 run. */
export function generateMigrationScript(
  tables: TableInfo[],
  views: ViewInfo[],
  overrides: TypeOverrides,
  source: SourceKind = 'sqlserver',
  database = '',
): { script: string; viewNotes: Record<string, string[]> } {
  const sourceLabel = { sqlserver: 'T-SQL', mysql: 'MySQL', postgres: 'PostgreSQL', oracle: 'Oracle', sqlite: 'SQLite' }[source];
  const parts: string[] = [
    '-- Generated by sqlserver-to-nhost-migrator',
    '-- Review before running against production. Views are converted',
    `-- from ${sourceLabel} with best-effort rules; check the notes below.`,
    '',
  ];
  const viewNotes: Record<string, string[]> = {};
  const knownNames = [...tables.map((t) => t.name), ...views.map((v) => v.name)];
  const knownColumns = tables.flatMap((t) => t.columns.map((c) => c.name));

  for (const t of tables) parts.push(generateCreateTable(t, overrides, source), '');
  for (const t of tables) {
    for (const ix of generateIndexes(t)) parts.push(ix);
  }
  if (tables.some((t) => t.indexes.length)) parts.push('');
  for (const t of tables) {
    for (const fk of generateForeignKeys(t)) parts.push(fk);
  }
  if (tables.some((t) => t.foreignKeys.length)) parts.push('');

  for (const v of views) {
    const { sql, notes } = generateCreateView(v, knownNames, knownColumns, source, database);
    if (notes.length) viewNotes[`${v.schema}.${v.name}`] = notes;
    parts.push(`-- View: ${v.schema}.${v.name}`);
    for (const n of notes) parts.push(`--   NOTE: ${n}`);
    parts.push(sql, '');
  }

  return { script: parts.join('\n'), viewNotes };
}

/** Statements in execution order for the live migration (views last,
 *  because they may reference the migrated tables). */
export function schemaStatements(
  tables: TableInfo[],
  views: ViewInfo[],
  overrides: TypeOverrides,
  source: SourceKind = 'sqlserver',
  database = '',
): { tables: string[]; fks: string[]; indexes: string[]; views: { name: string; sql: string; notes: string[] }[] } {
  return {
    tables: tables.map((t) => generateCreateTable(t, overrides, source)),
    fks: tables.flatMap((t) => generateForeignKeys(t)),
    indexes: tables.flatMap((t) => generateIndexes(t)),
    views: views.map((v) => {
      const { sql, notes } = generateCreateView(
        v,
        [...tables.map((t) => t.name), ...views.map((x) => x.name)],
        tables.flatMap((t) => t.columns.map((c) => c.name)),
        source,
        database,
      );
      return { name: `${v.schema}.${v.name}`, sql, notes };
    }),
  };
}
